// Builds dist/ — copies static files and injects Supabase config from environment.
// Run with `npm run build` (or `npm start`, which also serves the result).
const fs = require("fs");
const path = require("path");

// Load .env for local builds (no dependencies)
// — a tiny KEY=VALUE parser so we don't need the `dotenv` package.
// Real environment variables (Vercel) win over values found in the file.
const envFile = path.join(__dirname, ".env");
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !process.env[m[1]]) {
      // strip optional surrounding quotes: KEY="value" → value
      process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  }
}

// The two values every page needs to reach Supabase (see dist/config.js).
const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_ANON_KEY;

// Fail loudly instead of shipping a broken build.
if (!url || !key) {
  console.error("ERROR: SUPABASE_URL and SUPABASE_ANON_KEY must be set.");
  console.error("  Local:   copy .env.example to .env and fill in the values");
  console.error("  Vercel:  Project -> Settings -> Environment Variables");
  process.exit(1);
}

const root = __dirname;
const out = path.join(root, "dist");

// Start from a clean dist/ so deleted source files never linger in a deploy.
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

// 1) copy the static files the browser loads directly ...
for (const f of ["index.html", "styles.css", "manifest.json", "icon-180.png", "icon-192.png", "icon-512.png"]) {
  fs.copyFileSync(path.join(root, f), path.join(out, f));
}
fs.copyFileSync(path.join(root, "icon-192.png"), path.join(out, "favicon.ico")); /* PNG bytes; browsers sniff it, kills the 404 */
// 2) ... the bundled Supabase library, and ... (js/ is copied wholesale, so a new
// file under js/ needs no build change — just a <script> tag in index.html)
fs.cpSync(path.join(root, "vendor"), path.join(out, "vendor"), { recursive: true });
fs.cpSync(path.join(root, "js"), path.join(out, "js"), { recursive: true });   /* all app code */

// 3) write config.js: the ONLY generated file — core.js fails fast without it.
fs.writeFileSync(
  path.join(out, "config.js"),
  "// Generated by build.js - do not edit (values come from environment)\n" +
    "window.ENV = {\n" +
    `  SUPABASE_URL: ${JSON.stringify(url)},\n` +
    `  SUPABASE_ANON_KEY: ${JSON.stringify(key)},\n` +
    "};\n"
);

console.log("Built dist/ with Supabase config injected from environment.");
